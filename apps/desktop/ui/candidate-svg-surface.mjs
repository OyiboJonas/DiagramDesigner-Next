import {
  ConnectorGestureController,
  bindConnectorPointerSurface,
  buildOrthogonalPreviewPoints,
  normalizeConnectorKind,
} from "./editor-interaction/connector-gesture.mjs";
import {
  MoveGestureController,
  bindMovePointerSurface,
} from "./editor-interaction/move-gesture.mjs";
import { snapMoveDelta } from "./editor-interaction/snapping.mjs";

const SVG_NS = "http://www.w3.org/2000/svg";
const MOVE_OVERLAY_ATTRIBUTE = "data-ddn-move-overlay";
const MOVING_SOURCE_ATTRIBUTE = "data-ddn-moving-source";
const SELECTED_ATTRIBUTE = "data-ddn-selected";
const SNAP_GUIDES_ATTRIBUTE = "data-ddn-snap-guides";
const SNAP_GUIDE_ATTRIBUTE = "data-ddn-snap-guide";
const CONNECTOR_PREVIEW_ATTRIBUTE = "data-ddn-connector-preview";
const FORBIDDEN_SVG_SELECTOR = "script, foreignObject, iframe, object, embed";
const DEFAULT_INTERACTION_SETTINGS = Object.freeze({
  snappingEnabled: true,
  gridVisible: true,
  gridStepMm: 5,
  snapThresholdPx: 8,
});

/**
 * Desktop presentation adapter for the SVG *candidate* renderer.
 *
 * This module is intentionally outside editor/domain state. It consumes opaque
 * candidate SVG generated by Rust, performs candidate-specific DOM hit testing,
 * and feeds the renderer-agnostic move gesture controller. Replacing SVG after
 * ADR-019 therefore replaces this adapter rather than editor commands or DDNX.
 * Snap geometry is supplied separately in document millimetres; SVG DOM bounds
 * never become editor geometry.
 */
export function createCandidateSvgSurface(
  host,
  {
    commitMove,
    commitConnector = () => {},
    onError = (error) => {
      throw error;
    },
    onSelectionChange = () => {},
  } = {},
) {
  if (!host || typeof host.replaceChildren !== "function") {
    throw new TypeError("candidate SVG host must be a DOM element");
  }
  if (typeof commitMove !== "function") {
    throw new TypeError("commitMove must be a function");
  }
  if (typeof commitConnector !== "function") {
    throw new TypeError("commitConnector must be a function");
  }
  if (typeof onError !== "function" || typeof onSelectionChange !== "function") {
    throw new TypeError("candidate SVG callbacks must be functions");
  }

  let svg = null;
  let disposePointerBinding = null;
  let connectorController = null;
  let connectorTool = null;
  let selectedElementIds = [];
  let presentationGeometry = null;
  let interactionSettings = { ...DEFAULT_INTERACTION_SETTINGS };

  const applySelection = (elementIds, { notify = true } = {}) => {
    const requested = normalizeElementIds(elementIds);
    if (svg) {
      for (const element of svg.querySelectorAll(`[${SELECTED_ATTRIBUTE}]`)) {
        element.removeAttribute(SELECTED_ATTRIBUTE);
      }
    }

    const applied = [];
    if (svg) {
      for (const elementId of requested) {
        const element = findRenderableElement(svg, elementId);
        if (!element) {
          continue;
        }
        element.setAttribute(SELECTED_ATTRIBUTE, "true");
        applied.push(elementId);
      }
    }

    const changed = !sameIds(selectedElementIds, applied);
    selectedElementIds = applied;
    if (changed && notify) {
      onSelectionChange(Object.freeze([...selectedElementIds]));
    }
    return Object.freeze([...selectedElementIds]);
  };

  const clearSelection = (options) => applySelection([], options);

  const applyMovePreview = (preview) => {
    if (!svg) {
      return;
    }
    removeMoveOverlay(svg);
    if (!preview || !Array.isArray(preview.elementIds) || preview.elementIds.length === 0) {
      removeSnapGuides(svg);
      return;
    }

    const group = document.createElementNS(SVG_NS, "g");
    group.setAttribute(MOVE_OVERLAY_ATTRIBUTE, "true");
    group.setAttribute("pointer-events", "none");
    group.setAttribute("aria-hidden", "true");
    group.setAttribute(
      "transform",
      `translate(${formatFinite(preview.deltaMm?.x)} ${formatFinite(preview.deltaMm?.y)})`,
    );

    for (const elementId of preview.elementIds) {
      const source = findRenderableElement(svg, elementId);
      if (!source) {
        continue;
      }
      source.setAttribute(MOVING_SOURCE_ATTRIBUTE, "true");
      const clone = source.cloneNode(true);
      clone.removeAttribute(SELECTED_ATTRIBUTE);
      clone.removeAttribute(MOVING_SOURCE_ATTRIBUTE);
      group.append(clone);
    }

    if (group.childNodes.length > 0) {
      svg.append(group);
    }
  };

  const transformMoveDelta = ({ deltaMm, elementIds }) => {
    if (!svg || !presentationGeometry || !interactionSettings.snappingEnabled) {
      removeSnapGuides(svg);
      return deltaMm;
    }

    const rect = svg.getBoundingClientRect();
    const viewBox = svg.viewBox?.baseVal;
    if (!viewBox || rect.width <= 0 || rect.height <= 0) {
      removeSnapGuides(svg);
      return deltaMm;
    }
    const mmPerPx = Math.max(viewBox.width / rect.width, viewBox.height / rect.height);
    const snapped = snapMoveDelta({
      deltaMm,
      elementIds,
      elements: presentationGeometry.snapElements,
      pageSize: {
        width: presentationGeometry.widthMm,
        height: presentationGeometry.heightMm,
      },
      gridStepMm: interactionSettings.gridStepMm,
      thresholdMm: interactionSettings.snapThresholdPx * mmPerPx,
      gridEnabled: interactionSettings.gridVisible,
      objectEnabled: true,
    });
    renderSnapGuides(svg, presentationGeometry, snapped.guides);
    return snapped.deltaMm;
  };

  const bindPointerInteraction = () => {
    if (!svg) {
      return;
    }

    const screenToDocument = ({ xPx, yPx }) => {
      const rect = svg.getBoundingClientRect();
      const viewBox = svg.viewBox?.baseVal;
      if (!viewBox) {
        throw new Error("candidate SVG does not expose a viewBox");
      }
      return mapClientPointToViewBox(
        rect,
        { x: viewBox.x, y: viewBox.y, width: viewBox.width, height: viewBox.height },
        { xPx, yPx },
      );
    };

    const moveController = new MoveGestureController({
      screenToDocument,
      transformDelta: transformMoveDelta,
    });
    connectorController = new ConnectorGestureController({
      screenToDocument,
      minimumLengthMm: 0.5,
    });

    const disposeMove = bindMovePointerSurface(svg, {
      controller: moveController,
      resolveElementIds: (event) => {
        if (connectorTool !== null) {
          return null;
        }
        const target = event.target?.closest?.("[data-element-id]");
        if (!target || !svg.contains(target) || target.closest(`[${MOVE_OVERLAY_ATTRIBUTE}]`)) {
          clearSelection();
          return null;
        }
        const elementId = target.getAttribute("data-element-id");
        if (!elementId) {
          return null;
        }
        applySelection([elementId]);
        return [elementId];
      },
      onOverlay: applyMovePreview,
      onCommit: (commit) => {
        // Preserve the final preview while the single Rust move command is in flight.
        applyMovePreview(commit);
        Promise.resolve(commitMove(commit)).catch((error) => {
          removeMoveOverlay(svg);
          removeSnapGuides(svg);
          onError(error);
        });
      },
      onError,
    });

    const disposeConnector = bindConnectorPointerSurface(svg, {
      controller: connectorController,
      getConnectorKind: () => connectorTool,
      onOverlay: (preview) => renderConnectorPreview(svg, preview),
      onCommit: (commit) => {
        renderConnectorPreview(svg, { ...commit, kind: "connector-preview" });
        Promise.resolve(commitConnector(commit)).catch((error) => {
          removeConnectorPreview(svg);
          onError(error);
        });
      },
      onError,
    });

    disposePointerBinding = () => {
      disposeConnector();
      disposeMove();
      connectorController = null;
    };
  };

  return Object.freeze({
    setPresentation(presentation, { preserveSelection = true } = {}) {
      const previousSelection = preserveSelection ? [...selectedElementIds] : [];
      disposePointerBinding?.();
      disposePointerBinding = null;
      removeMoveOverlay(svg);
      removeSnapGuides(svg);
      removeConnectorPreview(svg);
      connectorController = null;
      clearSelection({ notify: false });
      host.replaceChildren();
      svg = null;
      presentationGeometry = null;

      if (!presentation?.svg) {
        applyGridStyle(host, presentationGeometry, interactionSettings);
        return;
      }
      validatePresentationSize(presentation.widthMm, presentation.heightMm);

      const parser = new DOMParser();
      const parsed = parser.parseFromString(presentation.svg, "image/svg+xml");
      const root = parsed.documentElement;
      if (root.namespaceURI !== SVG_NS || root.localName !== "svg") {
        throw new Error("candidate renderer did not return an SVG document");
      }
      if (parsed.querySelector("parsererror")) {
        throw new Error("candidate renderer returned malformed SVG");
      }
      assertSafeCandidateSvg(parsed);

      svg = document.importNode(root, true);
      svg.classList.add("candidate-svg-document");
      svg.removeAttribute("width");
      svg.removeAttribute("height");
      host.style.aspectRatio = `${presentation.widthMm} / ${presentation.heightMm}`;
      host.replaceChildren(svg);

      presentationGeometry = Object.freeze({
        widthMm: presentation.widthMm,
        heightMm: presentation.heightMm,
        // Geometry comes from Rust/document state. Filtering only removes elements
        // that the current renderer candidate did not actually materialize.
        snapElements: Object.freeze(
          normalizeSnapElements(presentation.snapElements ?? []).filter((element) =>
            Boolean(findRenderableElement(svg, element.elementId)),
          ),
        ),
      });
      applyGridStyle(host, presentationGeometry, interactionSettings);
      bindPointerInteraction();
      applySelection(previousSelection, { notify: false });
    },

    setConnectorTool(kind) {
      const next = kind === null ? null : normalizeConnectorKind(kind);
      if (connectorController?.isActive) {
        connectorController.cancel();
      }
      removeConnectorPreview(svg);
      connectorTool = next;
      if (next === null) {
        host.removeAttribute("data-connector-tool");
      } else {
        host.setAttribute("data-connector-tool", next);
      }
      return connectorTool;
    },

    setInteractionSettings(settings) {
      interactionSettings = normalizeInteractionSettings(interactionSettings, settings);
      applyGridStyle(host, presentationGeometry, interactionSettings);
      removeSnapGuides(svg);
      return Object.freeze({ ...interactionSettings });
    },

    setSelection(elementIds) {
      return applySelection(elementIds);
    },

    clearSelection() {
      return clearSelection();
    },

    clear() {
      disposePointerBinding?.();
      disposePointerBinding = null;
      removeMoveOverlay(svg);
      removeSnapGuides(svg);
      removeConnectorPreview(svg);
      connectorController = null;
      clearSelection();
      host.replaceChildren();
      svg = null;
      presentationGeometry = null;
      applyGridStyle(host, presentationGeometry, interactionSettings);
    },

    clearMovePreview() {
      removeMoveOverlay(svg);
      removeSnapGuides(svg);
    },

    clearConnectorPreview() {
      removeConnectorPreview(svg);
    },

    get selectedElementIds() {
      return Object.freeze([...selectedElementIds]);
    },

    dispose() {
      disposePointerBinding?.();
      disposePointerBinding = null;
      removeMoveOverlay(svg);
      removeSnapGuides(svg);
      removeConnectorPreview(svg);
      connectorController = null;
      clearSelection();
      host.replaceChildren();
      svg = null;
      presentationGeometry = null;
      applyGridStyle(host, presentationGeometry, interactionSettings);
    },
  });
}

export function mapClientPointToViewBox(rect, viewBox, point) {
  const values = [
    rect?.left,
    rect?.top,
    rect?.width,
    rect?.height,
    viewBox?.x,
    viewBox?.y,
    viewBox?.width,
    viewBox?.height,
    point?.xPx,
    point?.yPx,
  ];
  if (!values.every(Number.isFinite) || rect.width <= 0 || rect.height <= 0) {
    throw new TypeError("screen rectangle, viewBox and client point must contain finite geometry");
  }
  if (viewBox.width <= 0 || viewBox.height <= 0) {
    throw new TypeError("viewBox width and height must be greater than zero");
  }
  return Object.freeze({
    x: viewBox.x + ((point.xPx - rect.left) / rect.width) * viewBox.width,
    y: viewBox.y + ((point.yPx - rect.top) / rect.height) * viewBox.height,
  });
}

function validatePresentationSize(widthMm, heightMm) {
  if (!Number.isFinite(widthMm) || !Number.isFinite(heightMm) || widthMm <= 0 || heightMm <= 0) {
    throw new TypeError("candidate presentation must contain a positive finite page size");
  }
}

function assertSafeCandidateSvg(documentNode) {
  if (documentNode.querySelector(FORBIDDEN_SVG_SELECTOR)) {
    throw new Error("candidate renderer returned forbidden active SVG content");
  }
  for (const element of documentNode.querySelectorAll("*")) {
    for (const attribute of element.attributes) {
      if (attribute.name.toLowerCase().startsWith("on")) {
        throw new Error("candidate renderer returned an event-handler attribute");
      }
    }
  }
}

function removeMoveOverlay(svg) {
  if (!svg) {
    return;
  }
  for (const overlay of svg.querySelectorAll(`[${MOVE_OVERLAY_ATTRIBUTE}]`)) {
    overlay.remove();
  }
  for (const source of svg.querySelectorAll(`[${MOVING_SOURCE_ATTRIBUTE}]`)) {
    source.removeAttribute(MOVING_SOURCE_ATTRIBUTE);
  }
}

function removeConnectorPreview(svg) {
  if (!svg) {
    return;
  }
  for (const preview of svg.querySelectorAll(`[${CONNECTOR_PREVIEW_ATTRIBUTE}]`)) {
    preview.remove();
  }
}

function renderConnectorPreview(svg, preview) {
  removeConnectorPreview(svg);
  if (!svg || preview?.kind !== "connector-preview") {
    return;
  }
  const start = preview.startMm;
  const end = preview.endMm;
  const element =
    preview.connectorKind === "orthogonal"
      ? document.createElementNS(SVG_NS, "polyline")
      : document.createElementNS(SVG_NS, "line");
  element.setAttribute(CONNECTOR_PREVIEW_ATTRIBUTE, preview.connectorKind);
  element.setAttribute("pointer-events", "none");
  element.setAttribute("aria-hidden", "true");
  if (preview.connectorKind === "orthogonal") {
    const points = buildOrthogonalPreviewPoints(start, end);
    element.setAttribute(
      "points",
      points.map((point) => `${formatFinite(point.x)},${formatFinite(point.y)}`).join(" "),
    );
  } else {
    element.setAttribute("x1", formatFinite(start?.x));
    element.setAttribute("y1", formatFinite(start?.y));
    element.setAttribute("x2", formatFinite(end?.x));
    element.setAttribute("y2", formatFinite(end?.y));
  }
  svg.append(element);
}

function removeSnapGuides(svg) {
  if (!svg) {
    return;
  }
  for (const guide of svg.querySelectorAll(`[${SNAP_GUIDES_ATTRIBUTE}]`)) {
    guide.remove();
  }
}

function renderSnapGuides(svg, geometry, guides) {
  removeSnapGuides(svg);
  if (!guides?.x && !guides?.y) {
    return;
  }
  const group = document.createElementNS(SVG_NS, "g");
  group.setAttribute(SNAP_GUIDES_ATTRIBUTE, "true");
  group.setAttribute("pointer-events", "none");
  group.setAttribute("aria-hidden", "true");

  if (guides.x) {
    group.append(createSnapGuideLine("x", guides.x, geometry));
  }
  if (guides.y) {
    group.append(createSnapGuideLine("y", guides.y, geometry));
  }
  svg.append(group);
}

function createSnapGuideLine(axis, guide, geometry) {
  const line = document.createElementNS(SVG_NS, "line");
  line.setAttribute(SNAP_GUIDE_ATTRIBUTE, axis);
  line.setAttribute("data-ddn-snap-source", guide.source);
  if (axis === "x") {
    line.setAttribute("x1", formatFinite(guide.positionMm));
    line.setAttribute("x2", formatFinite(guide.positionMm));
    line.setAttribute("y1", "0");
    line.setAttribute("y2", formatFinite(geometry.heightMm));
  } else {
    line.setAttribute("x1", "0");
    line.setAttribute("x2", formatFinite(geometry.widthMm));
    line.setAttribute("y1", formatFinite(guide.positionMm));
    line.setAttribute("y2", formatFinite(guide.positionMm));
  }
  return line;
}

function findRenderableElement(svg, elementId) {
  for (const element of svg.querySelectorAll("[data-element-id]")) {
    if (element.closest(`[${MOVE_OVERLAY_ATTRIBUTE}]`)) {
      continue;
    }
    if (element.getAttribute("data-element-id") === elementId) {
      return element;
    }
  }
  return null;
}

function normalizeSnapElements(elements) {
  if (!Array.isArray(elements)) {
    throw new TypeError("candidate snapElements must be an array");
  }
  const normalized = [];
  const seen = new Set();
  for (const element of elements) {
    if (typeof element?.elementId !== "string" || element.elementId.length === 0) {
      throw new TypeError("candidate snap element IDs must be non-empty strings");
    }
    if (seen.has(element.elementId)) {
      throw new TypeError(`duplicate candidate snap element ID: ${element.elementId}`);
    }
    seen.add(element.elementId);
    normalized.push(
      Object.freeze({
        elementId: element.elementId,
        boundsMm: Object.freeze({ ...element.boundsMm }),
        rotationDeg: element.rotationDeg,
      }),
    );
  }
  return normalized;
}

function normalizeInteractionSettings(current, patch) {
  if (patch == null || typeof patch !== "object") {
    throw new TypeError("interaction settings must be an object");
  }
  const next = { ...current, ...patch };
  if (typeof next.snappingEnabled !== "boolean" || typeof next.gridVisible !== "boolean") {
    throw new TypeError("snappingEnabled and gridVisible must be booleans");
  }
  if (!Number.isFinite(next.gridStepMm) || next.gridStepMm <= 0) {
    throw new TypeError("gridStepMm must be finite and greater than zero");
  }
  if (!Number.isFinite(next.snapThresholdPx) || next.snapThresholdPx < 0) {
    throw new TypeError("snapThresholdPx must be finite and non-negative");
  }
  return next;
}

function applyGridStyle(host, geometry, settings) {
  const visible = Boolean(geometry && settings.gridVisible);
  host.dataset.gridVisible = visible ? "true" : "false";
  if (!geometry) {
    host.style.removeProperty("--ddn-grid-step-x");
    host.style.removeProperty("--ddn-grid-step-y");
    return;
  }
  host.style.setProperty("--ddn-grid-step-x", `${(settings.gridStepMm / geometry.widthMm) * 100}%`);
  host.style.setProperty("--ddn-grid-step-y", `${(settings.gridStepMm / geometry.heightMm) * 100}%`);
}

function normalizeElementIds(elementIds) {
  if (elementIds == null || typeof elementIds[Symbol.iterator] !== "function") {
    throw new TypeError("selection element IDs must be iterable");
  }
  const normalized = [];
  const seen = new Set();
  for (const elementId of elementIds) {
    if (typeof elementId !== "string" || elementId.length === 0) {
      throw new TypeError("selection element IDs must be non-empty strings");
    }
    if (!seen.has(elementId)) {
      seen.add(elementId);
      normalized.push(elementId);
    }
  }
  return normalized;
}

function sameIds(left, right) {
  return left.length === right.length && left.every((value, index) => value === right[index]);
}

function formatFinite(value) {
  if (!Number.isFinite(value)) {
    throw new TypeError("move preview delta must be finite");
  }
  const normalized = Object.is(value, -0) ? 0 : value;
  return Number(normalized.toFixed(6)).toString();
}
